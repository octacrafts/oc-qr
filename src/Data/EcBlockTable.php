    /**
     * @return list<array{data: list<int>, ecCount: int}>
     */
    public static function splitBlocks(array $dataCodewords, int $version, ErrorCorrectionLevel $level): array
    {
        $spec = self::BLOCKS[$version][$level->value];
        [$numG1, $dataG1, $numG2, $dataG2, $ecCount] = $spec;

        $blocks = [];
        $offset = 0;

        for ($i = 0; $i < $numG1; $i++) {
            $blocks[] = [
                'data' => array_slice($dataCodewords, $offset, $dataG1),
                'ecCount' => $ecCount,
            ];
            $offset += $dataG1;
        }

        for ($i = 0; $i < $numG2; $i++) {
            $blocks[] = [
                'data' => array_slice($dataCodewords, $offset, $dataG2),
                'ecCount' => $ecCount,
            ];
            $offset += $dataG2;
        }

        return $blocks;
    }
